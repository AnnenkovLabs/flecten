#!/usr/bin/env bun
// Downloads provider logos from models.dev into ui/public/provider-logos and writes the
// generated lookup module. Run manually when the models.dev provider list changes:
//   bun scripts/sync-provider-logos.mjs
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const logoDir = join(root, "ui/public/provider-logos");
const moduleFile = join(root, "ui/src/lib/provider-logos.generated.ts");
const API_URL = "https://models.dev/api.json";
const LOGO_URL = (id) => `https://models.dev/logos/${encodeURIComponent(id)}.svg`;
const MAX_LOGO_BYTES = 64 * 1024;
const FORBIDDEN = ["<script", "<foreignobject", "javascript:", 'href="http', "href='http"];

function hasEventHandler(lower) {
  for (const token of lower.split(/[\s<]+/)) {
    if (token.startsWith("on") && token.includes("=")) return true;
  }
  return false;
}

function validLogo(text) {
  const lower = text.trimStart().toLowerCase();
  if (!lower.startsWith("<svg") && !lower.startsWith("<?xml")) return "not an svg document";
  if (text.length > MAX_LOGO_BYTES) return `larger than ${MAX_LOGO_BYTES} bytes`;
  for (const token of FORBIDDEN) if (lower.includes(token)) return `contains ${token}`;
  if (hasEventHandler(lower)) return "event handler attribute";
  return undefined;
}

const LOCAL_HOSTS = new Set(["localhost", "127.0.0.1", "0.0.0.0", "[::1]", "::1"]);

function hostOf(url) {
  if (typeof url !== "string" || url.length === 0) return undefined;
  try {
    const host = new URL(url).hostname.toLowerCase();
    return LOCAL_HOSTS.has(host) ? undefined : host;
  } catch {
    return undefined;
  }
}

async function fetchText(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(20_000) });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.text();
}

const api = JSON.parse(await fetchText(API_URL));
const ids = Object.keys(api).sort();
await mkdir(logoDir, { recursive: true });
for (const name of await readdir(logoDir)) await rm(join(logoDir, name));

const saved = [];
const skipped = [];
const hosts = new Map();
let index = 0;
async function worker() {
  while (index < ids.length) {
    const id = ids[index++];
    try {
      const svg = await fetchText(LOGO_URL(id));
      const problem = validLogo(svg);
      if (problem !== undefined) {
        skipped.push(`${id}: ${problem}`);
        continue;
      }
      await writeFile(join(logoDir, `${id}.svg`), `${svg.trim()}\n`);
      saved.push(id);
      const host = hostOf(api[id]?.api);
      if (host !== undefined && !hosts.has(host)) hosts.set(host, id);
    } catch (error) {
      skipped.push(`${id}: ${error instanceof Error ? error.message : String(error)}`);
    }
  }
}
await Promise.all(Array.from({ length: 8 }, worker));
saved.sort();

const hostEntries = [...hosts.entries()].sort(([a], [b]) => a.localeCompare(b));
const source = `// Generated by scripts/sync-provider-logos.mjs from ${API_URL}. Do not edit by hand.
// Logos: models.dev (MIT), served from ui/public/provider-logos.

export const PROVIDER_LOGO_IDS: ReadonlySet<string> = new Set([
${saved.map((id) => `  ${JSON.stringify(id)},`).join("\n")}
]);

export const PROVIDER_LOGO_HOSTS: Readonly<Record<string, string>> = {
${hostEntries.map(([host, id]) => `  ${JSON.stringify(host)}: ${JSON.stringify(id)},`).join("\n")}
};
`;
await writeFile(moduleFile, source);
console.log(`provider logos: ${saved.length} saved, ${skipped.length} skipped`);
for (const line of skipped) console.log(`  skipped ${line}`);
